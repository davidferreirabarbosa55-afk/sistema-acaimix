create or replace function public.api_cardapio(p jsonb default '{}') returns jsonb
language sql stable set search_path = '' as $$
  select jsonb_build_object(
    'categorias', coalesce((
      select jsonb_agg(jsonb_build_object('id', c.id, 'nome', c.nome, 'produtos', prods) order by c.ordem, c.id)
      from acaimix.categorias c
      cross join lateral (
        select jsonb_agg(jsonb_build_object('id', pr.id, 'categoria_id', pr.categoria_id, 'nome', pr.nome, 'descricao', pr.descricao,
                 'preco_centavos', pr.preco_centavos, 'emoji', pr.emoji, 'imagem', pr.imagem,
                 'permite_adicionais', pr.permite_adicionais, 'destaque', pr.destaque) order by pr.ordem, pr.id) as prods
        from acaimix.produtos pr where pr.categoria_id = c.id and pr.disponivel and not pr.arquivado
      ) x
      where prods is not null), '[]'::jsonb),
    'adicionais', coalesce((select jsonb_agg(jsonb_build_object('id', id, 'nome', nome, 'preco_centavos', preco_centavos) order by ordem, id)
                            from acaimix.adicionais where disponivel), '[]'::jsonb))
$$;

-- Cria o pedido inteiro numa transação. O navegador manda só ids e quantidades;
-- os preços (produto + adicionais) saem do banco.
create or replace function public.api_criar_pedido(p jsonb) returns jsonb
language plpgsql set search_path = '' as $$
declare
  v_forma text := p->>'forma_pagamento';
  v_item jsonb; v_prod acaimix.produtos; v_qtd int; v_ids bigint[]; v_adic record;
  v_unit int; v_nomes text; v_total int := 0; v_pedido acaimix.pedidos; v_letras text := 'ABCDEFGHJKLMNPQRSTUVWXYZ';
  v_itens jsonb := '[]'::jsonb;
begin
  if acaimix.cfg('loja_aberta') <> 'true' then perform acaimix.erro('Estamos fechados no momento. Volte mais tarde! 💜'); end if;
  if v_forma = 'balcao' and acaimix.cfg('permitir_balcao') <> 'true' then perform acaimix.erro('Pagamento no balcão indisponível.'); end if;
  if jsonb_typeof(p->'itens') <> 'array' or jsonb_array_length(p->'itens') = 0 or jsonb_array_length(p->'itens') > 30 then
    perform acaimix.erro('Sacola vazia ou inválida.');
  end if;

  for v_item in select * from jsonb_array_elements(p->'itens') loop
    v_qtd := case when jsonb_typeof(v_item->'quantidade') = 'number' and (v_item->>'quantidade') ~ '^\d+$' then (v_item->>'quantidade')::int end;
    if v_qtd is null or v_qtd < 1 or v_qtd > 20 then perform acaimix.erro('Quantidade inválida.'); end if;

    select * into v_prod from acaimix.produtos
     where id = case when (v_item->>'produto_id') ~ '^\d{1,15}$' then (v_item->>'produto_id')::bigint end
       and disponivel and not arquivado;
    if not found then perform acaimix.erro('Um dos itens não está mais disponível. Atualize o cardápio.'); end if;

    -- adicionais: sem repetição, na ordem escolhida
    select coalesce(array_agg(id order by ord), '{}') into v_ids from (
      select distinct on (x.v::bigint) x.v::bigint as id, x.ord
      from jsonb_array_elements_text(case when jsonb_typeof(v_item->'adicionais') = 'array' then v_item->'adicionais' else '[]' end)
           with ordinality as x(v, ord)
      where x.v ~ '^\d{1,15}$'
      order by x.v::bigint, x.ord) d;
    if cardinality(v_ids) > 0 and not v_prod.permite_adicionais then perform acaimix.erro(v_prod.nome || ' não aceita adicionais.'); end if;
    if cardinality(v_ids) > 15 then perform acaimix.erro('Muitos adicionais em um item.'); end if;

    v_unit := v_prod.preco_centavos; v_nomes := '';
    for v_adic in select a.id, a.nome, a.preco_centavos, a.disponivel, u.ord
                  from unnest(v_ids) with ordinality as u(id, ord) left join acaimix.adicionais a on a.id = u.id order by u.ord loop
      if v_adic.nome is null or not v_adic.disponivel then perform acaimix.erro('Um adicional não está mais disponível. Atualize o cardápio.'); end if;
      v_unit := v_unit + v_adic.preco_centavos;
      v_nomes := v_nomes || case when v_nomes = '' then '' else ', ' end || v_adic.nome;
    end loop;

    v_total := v_total + v_unit * v_qtd;
    v_itens := v_itens || jsonb_build_object('produto_id', v_prod.id, 'nome', v_prod.nome, 'preco_centavos', v_unit,
                 'quantidade', v_qtd, 'observacao', left(coalesce(v_item->>'observacao', ''), 140), 'adicionais', v_nomes);
  end loop;

  insert into acaimix.pedidos (token, cliente_nome, cliente_telefone, cliente_email, tipo, mesa, observacao, forma_pagamento, total_centavos, status)
  values (p->>'token', p->>'nome', coalesce(p->>'telefone', ''), coalesce(p->>'email', ''), p->>'tipo', coalesce(p->>'mesa', ''),
          coalesce(p->>'observacao', ''), v_forma, v_total, case when v_forma = 'balcao' then 'recebido' else 'aguardando_pagamento' end)
  returning * into v_pedido;

  update acaimix.pedidos set codigo = substr(v_letras, ((id / 1000) % 24)::int + 1, 1) || lpad((id % 1000)::text, 3, '0')
   where id = v_pedido.id returning * into v_pedido;

  insert into acaimix.itens_pedido (pedido_id, produto_id, nome, preco_centavos, quantidade, observacao, adicionais)
  select v_pedido.id, (i->>'produto_id')::bigint, i->>'nome', (i->>'preco_centavos')::int, (i->>'quantidade')::int, i->>'observacao', i->>'adicionais'
  from jsonb_array_elements(v_itens) i;

  return jsonb_build_object('id', v_pedido.id, 'codigo', v_pedido.codigo, 'total_centavos', v_total, 'itens', v_itens,
                            'cliente', acaimix.pedido_cliente_json(v_pedido));
end $$;

create or replace function public.api_registrar_pagamento(p jsonb) returns jsonb
language plpgsql set search_path = '' as $$
declare v acaimix.pedidos;
begin
  insert into acaimix.pagamentos (pedido_id, provedor, metodo, id_externo, status, valor_centavos, pix_copia_cola, pix_qr_base64, checkout_url)
  values ((p->>'pedido_id')::bigint, p->>'provedor', p->>'metodo', p->>'id_externo', p->>'status', (p->>'valor_centavos')::int,
          p->>'pix_copia_cola', p->>'pix_qr_base64', p->>'checkout_url');
  select * into v from acaimix.pedidos where id = (p->>'pedido_id')::bigint;
  return jsonb_build_object('ok', true, 'cliente', acaimix.pedido_cliente_json(v));
end $$;

create or replace function public.api_cancelar_pedido_sistema(p jsonb) returns jsonb
language sql set search_path = '' as $$
  update acaimix.pedidos set status = 'cancelado', atualizado_em = now() where id = (p->>'pedido_id')::bigint and status = 'aguardando_pagamento';
  select '{"ok":true}'::jsonb
$$;

create or replace function public.api_pedido_cliente(p jsonb) returns jsonb
language plpgsql stable set search_path = '' as $$
declare v acaimix.pedidos;
begin
  select * into v from acaimix.pedidos where token = p->>'token';
  if not found then perform acaimix.erro('Pedido não encontrado.', 404); end if;
  return acaimix.pedido_cliente_json(v) || jsonb_build_object('id', v.id,
    'ids_pagamento', (select coalesce(jsonb_agg(id_externo), '[]') from acaimix.pagamentos
                      where pedido_id = v.id and provedor = 'mercadopago' and id_externo not like 'pref-%'));
end $$;

create or replace function public.api_simular_pagamento(p jsonb) returns jsonb
language plpgsql set search_path = '' as $$
declare v acaimix.pedidos;
begin
  select * into v from acaimix.pedidos where token = p->>'token' for update;
  if not found then perform acaimix.erro('Pedido não encontrado.', 404); end if;
  if v.status = 'aguardando_pagamento' then
    update acaimix.pagamentos set status = 'approved', atualizado_em = now() where pedido_id = v.id;
    update acaimix.pedidos set status = 'recebido', atualizado_em = now() where id = v.id returning * into v;
  end if;
  return acaimix.pedido_cliente_json(v);
end $$;

-- Aplica um pagamento CONSULTADO na API do Mercado Pago (nunca o corpo do webhook).
create or replace function public.api_aplicar_pagamento(p jsonb) returns jsonb
language plpgsql set search_path = '' as $$
declare v acaimix.pedidos; v_valor int := (p->>'valor_centavos')::int; v_status text := p->>'status';
begin
  select * into v from acaimix.pedidos where id = (p->>'pedido_id')::bigint for update;
  if not found then return '{"resultado":"pedido_inexistente"}'; end if;

  insert into acaimix.pagamentos (pedido_id, provedor, metodo, id_externo, status, valor_centavos)
  values (v.id, 'mercadopago', p->>'metodo', p->>'id', v_status, v_valor)
  on conflict (provedor, id_externo) do update set status = excluded.status, atualizado_em = now();

  if v_status <> 'approved' then return '{"resultado":"sem_mudanca"}'; end if;

  if v.status = 'cancelado' then
    perform acaimix.registrar('sistema', 'ALERTA: pagamento em pedido cancelado',
      format('Pedido %s, pagamento %s: reembolsar no Mercado Pago', v.codigo, p->>'id'), '');
    return jsonb_build_object('resultado', 'alerta_cancelado', 'codigo', v.codigo);
  end if;
  if v.status <> 'aguardando_pagamento' then return '{"resultado":"ja_liberado"}'; end if;
  if v_valor <> v.total_centavos then
    perform acaimix.registrar('sistema', 'ALERTA: valor pago diferente',
      format('Pedido %s: pago %s, total %s', v.codigo, acaimix.reais(v_valor), acaimix.reais(v.total_centavos)), '');
    return jsonb_build_object('resultado', 'alerta_valor', 'codigo', v.codigo);
  end if;

  update acaimix.pedidos set status = 'recebido', atualizado_em = now() where id = v.id;
  return jsonb_build_object('resultado', 'liberado', 'codigo', v.codigo);
end $$;

