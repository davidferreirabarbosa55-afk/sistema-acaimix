-- ---------------------------------------------------------------- admin: resumo e pedidos
create or replace function public.api_resumo(p jsonb) returns jsonb
language plpgsql stable set search_path = '' as $$
declare
  v_fuso interval := make_interval(hours => coalesce((p->>'fuso')::int, -3));
  v_hoje date := ((now() at time zone 'UTC') + v_fuso)::date;
  v_res jsonb; v_ped int; v_fat bigint;
begin
  select count(*), coalesce(sum(total_centavos), 0) into v_ped, v_fat from acaimix.pedidos
   where status not in ('aguardando_pagamento','cancelado') and ((criado_em at time zone 'UTC') + v_fuso)::date = v_hoje;
  v_res := jsonb_build_object(
    'hoje', jsonb_build_object('pedidos', v_ped, 'faturamento', v_fat,
             'ticket_medio', case when v_ped > 0 then round(v_fat::numeric / v_ped) else 0 end,
             'em_andamento', (select count(*) from acaimix.pedidos where status in ('recebido','em_preparo','pronto'))),
    'dias', coalesce((select jsonb_agg(jsonb_build_object('dia', dia, 'pedidos', n, 'faturamento', fat) order by dia) from (
              select ((criado_em at time zone 'UTC') + v_fuso)::date as dia, count(*) n, sum(total_centavos) fat
              from acaimix.pedidos where status not in ('aguardando_pagamento','cancelado')
                and ((criado_em at time zone 'UTC') + v_fuso)::date >= v_hoje - 6 group by 1) d), '[]'),
    'mais_vendidos', coalesce((select jsonb_agg(jsonb_build_object('nome', nome, 'quantidade', q, 'total', t) order by q desc) from (
              select i.nome, sum(i.quantidade) q, sum(i.quantidade * i.preco_centavos) t
              from acaimix.itens_pedido i join acaimix.pedidos pe on pe.id = i.pedido_id
              where pe.status not in ('aguardando_pagamento','cancelado') and ((pe.criado_em at time zone 'UTC') + v_fuso)::date >= v_hoje - 29
              group by i.nome order by q desc limit 5) m), '[]'),
    'alertas', coalesce((select jsonb_agg(jsonb_build_object('quando', acaimix.iso(quando), 'acao', acao, 'detalhe', detalhe) order by id desc) from (
              select * from acaimix.auditoria where (acao like 'ALERTA%' or detalhe like '%reembolsar%')
                and quando >= now() - interval '7 days' order by id desc limit 5) a), '[]'));
  return v_res;
end $$;

