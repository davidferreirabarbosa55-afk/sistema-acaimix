  delete from acaimix.usuarios where id = (p->>'id')::bigint returning usuario into v_nome;
  if v_nome is not null then perform acaimix.registrar(p->>'por', 'excluiu usuário', v_nome, p->>'ip'); end if;
  return '{"ok":true}';
end $$;

-- ---------------------------------------------------------------- manutenção (cron diário da Vercel)
-- LGPD: depois de N dias, nome/telefone/e-mail dos clientes são apagados (os números de venda ficam).
create or replace function public.api_manutencao(p jsonb) returns jsonb
language plpgsql set search_path = '' as $$
declare v_anon int; v_canc int;
begin
  update acaimix.pedidos set cliente_nome = 'Cliente', cliente_telefone = '', cliente_email = ''
   where criado_em < now() - make_interval(days => greatest(7, coalesce((p->>'retencao_dias')::int, 180)))
     and (cliente_telefone <> '' or cliente_email <> '' or cliente_nome <> 'Cliente');
  get diagnostics v_anon = row_count;
  update acaimix.pagamentos set pix_copia_cola = null, pix_qr_base64 = null where criado_em < now() - interval '2 days' and pix_qr_base64 is not null;
  update acaimix.pedidos set status = 'cancelado', atualizado_em = now()
   where status = 'aguardando_pagamento' and criado_em < now() - interval '2 hours';
  get diagnostics v_canc = row_count;
  delete from acaimix.sessoes where expira_em < now();
  delete from acaimix.limites where inicio < now() - interval '1 day';
  delete from acaimix.auditoria where quando < now() - interval '365 days';
  return jsonb_build_object('anonimizados', v_anon, 'cancelados', v_canc);
end $$;

-- ---------------------------------------------------------------- backup (npm run backup)
create or replace function public.api_exportar(p jsonb default '{}') returns jsonb
language sql stable set search_path = '' as $$
  select jsonb_build_object(
    'gerado_em', acaimix.iso(now()), 'versao', 1,
    'configuracoes', (select coalesce(jsonb_agg(to_jsonb(t)), '[]') from acaimix.configuracoes t),
    'categorias',    (select coalesce(jsonb_agg(to_jsonb(t) order by id), '[]') from acaimix.categorias t),
    'produtos',      (select coalesce(jsonb_agg(to_jsonb(t) order by id), '[]') from acaimix.produtos t),
    'adicionais',    (select coalesce(jsonb_agg(to_jsonb(t) order by id), '[]') from acaimix.adicionais t),
    'pedidos',       (select coalesce(jsonb_agg(to_jsonb(t) - 'token' order by id), '[]') from acaimix.pedidos t),
    'itens_pedido',  (select coalesce(jsonb_agg(to_jsonb(t) order by id), '[]') from acaimix.itens_pedido t),
    'pagamentos',    (select coalesce(jsonb_agg(to_jsonb(t) - 'pix_qr_base64' - 'pix_copia_cola' order by id), '[]') from acaimix.pagamentos t),
    'usuarios',      (select coalesce(jsonb_agg(jsonb_build_object('usuario', usuario, 'papel', papel) order by id), '[]') from acaimix.usuarios),
    'auditoria',     (select coalesce(jsonb_agg(to_jsonb(t) order by id), '[]') from acaimix.auditoria t))
$$;

-- ---------------------------------------------------------------- permissões
-- Só a chave secreta (service_role) usa o schema e executa as funções da API.
grant usage on schema acaimix to service_role;
grant select, insert, update, delete on all tables in schema acaimix to service_role;
grant usage, select on all sequences in schema acaimix to service_role;
grant execute on all functions in schema acaimix to service_role;

do $$
declare f record;
begin
  for f in select p.oid::regprocedure as assinatura from pg_proc p join pg_namespace n on n.oid = p.pronamespace
           where n.nspname = 'public' and p.proname like 'api\_%' loop
    execute format('revoke all on function %s from public', f.assinatura);
    if exists (select 1 from pg_roles where rolname = 'anon') then execute format('revoke all on function %s from anon', f.assinatura); end if;
    if exists (select 1 from pg_roles where rolname = 'authenticated') then execute format('revoke all on function %s from authenticated', f.assinatura); end if;
    execute format('grant execute on function %s to service_role', f.assinatura);
  end loop;
end $$;

