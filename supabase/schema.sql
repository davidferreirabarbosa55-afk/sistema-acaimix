-- =====================================================================
-- Açaí Mix · banco de dados no Supabase (Postgres)
--
-- Como usar: Supabase › SQL Editor › New query › cole TODO este arquivo › Run.
-- Pode rodar de novo sem perder dados (cria só o que ainda não existe e
-- atualiza as funções).
--
-- Segurança:
--  * As tabelas ficam no schema "acaimix", que NÃO é exposto pela API do Supabase.
--  * A API só enxerga as funções "api_*" do schema public, e só a CHAVE SECRETA
--    (service_role) pode executá-las. A chave pública (anon) não acessa nada.
--  * Preços, adicionais e regras do pedido são calculados AQUI, dentro do banco.
--  * Valores em dinheiro são sempre em CENTAVOS (inteiros).
-- =====================================================================

create schema if not exists acaimix;
revoke all on schema acaimix from public;

-- ---------------------------------------------------------------- tabelas
create table if not exists acaimix.categorias (
  id     bigint generated by default as identity primary key,
  nome   text not null unique,
  ordem  int  not null default 0
);

create table if not exists acaimix.produtos (
  id                 bigint generated by default as identity primary key,
  categoria_id       bigint not null references acaimix.categorias(id),
  nome               text   not null,
  descricao          text   not null default '',
  preco_centavos     int    not null check (preco_centavos > 0),
  emoji              text   not null default '🍧',
  imagem             text   not null default '',
  disponivel         boolean not null default true,
  permite_adicionais boolean not null default false,
  destaque           boolean not null default false,
  arquivado          boolean not null default false,
  ordem              int    not null default 0
);

create table if not exists acaimix.adicionais (
  id              bigint generated by default as identity primary key,
  nome            text not null,
  preco_centavos  int  not null default 0 check (preco_centavos >= 0),
  disponivel      boolean not null default true,
  ordem           int  not null default 0
);

create table if not exists acaimix.configuracoes (
  chave  text primary key,
  valor  text not null
);

create table if not exists acaimix.pedidos (
  id               bigint generated by default as identity primary key,
  codigo           text not null default '',
  token            text not null unique,
  cliente_nome     text not null,
  cliente_telefone text not null default '',
  cliente_email    text not null default '',
  tipo             text not null check (tipo in ('retirada','mesa')),
  mesa             text not null default '',
  observacao       text not null default '',
  forma_pagamento  text not null check (forma_pagamento in ('pix','cartao','balcao')),
  total_centavos   int  not null,
  status           text not null check (status in ('aguardando_pagamento','recebido','em_preparo','pronto','entregue','cancelado')),
  criado_em        timestamptz not null default now(),
  atualizado_em    timestamptz not null default now()
);
create index if not exists idx_pedidos_status on acaimix.pedidos(status);
create index if not exists idx_pedidos_criado on acaimix.pedidos(criado_em);

create table if not exists acaimix.itens_pedido (
  id              bigint generated by default as identity primary key,
  pedido_id       bigint not null references acaimix.pedidos(id) on delete cascade,
  produto_id      bigint not null references acaimix.produtos(id),
  nome            text not null,
  preco_centavos  int  not null,          -- preço unitário JÁ com adicionais
  quantidade      int  not null check (quantidade between 1 and 50),
  observacao      text not null default '',
  adicionais      text not null default ''
);
create index if not exists idx_itens_pedido on acaimix.itens_pedido(pedido_id);
create index if not exists idx_itens_produto on acaimix.itens_pedido(produto_id);

create table if not exists acaimix.pagamentos (
  id              bigint generated by default as identity primary key,
  pedido_id       bigint not null references acaimix.pedidos(id) on delete cascade,
  provedor        text not null,
  metodo          text not null,
  id_externo      text,
  status          text not null,
  valor_centavos  int  not null,
  pix_copia_cola  text,
  pix_qr_base64   text,
  checkout_url    text,
  criado_em       timestamptz not null default now(),
  atualizado_em   timestamptz not null default now(),
  unique (provedor, id_externo)
);
create index if not exists idx_pag_pedido on acaimix.pagamentos(pedido_id);

create table if not exists acaimix.usuarios (
  id          bigint generated by default as identity primary key,
  usuario     text not null unique,
  senha_hash  text not null,
  papel       text not null default 'cozinha' check (papel in ('admin','cozinha'))
);

create table if not exists acaimix.sessoes (
  token_hash  text primary key,
  usuario_id  bigint not null references acaimix.usuarios(id) on delete cascade,
  expira_em   timestamptz not null
);

create table if not exists acaimix.auditoria (
  id       bigint generated by default as identity primary key,
  quando   timestamptz not null default now(),
  usuario  text not null,
  acao     text not null,
  detalhe  text not null default '',
  ip       text not null default ''
);
create index if not exists idx_auditoria_quando on acaimix.auditoria(quando);

create table if not exists acaimix.limites (
  chave   text primary key,
  inicio  timestamptz not null,
  n       int not null
);

