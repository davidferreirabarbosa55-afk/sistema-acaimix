create or replace function public.api_produto_salvar(p jsonb) returns jsonb
language plpgsql set search_path = '' as $$
declare v_id bigint := nullif(p->>'id', '')::bigint; v_antes acaimix.produtos; v_preco int := (p->>'preco_centavos')::int;
        v_disp boolean := (p->>'disponivel')::boolean; v_mud text[] := '{}';
begin
  if not exists (select 1 from acaimix.categorias where id = (p->>'categoria_id')::bigint) then perform acaimix.erro('Escolha uma categoria.'); end if;
  if v_id is null then
    insert into acaimix.produtos (categoria_id, nome, descricao, preco_centavos, emoji, disponivel, permite_adicionais, destaque, ordem)
    values ((p->>'categoria_id')::bigint, p->>'nome', p->>'descricao', v_preco, p->>'emoji', v_disp,
            (p->>'permite_adicionais')::boolean, (p->>'destaque')::boolean,
            (select coalesce(max(ordem), -1) + 1 from acaimix.produtos where categoria_id = (p->>'categoria_id')::bigint))
    returning id into v_id;
    perform acaimix.registrar(p->>'usuario', 'criou produto', format('%s por %s', p->>'nome', acaimix.reais(v_preco)), p->>'ip');
  else
    select * into v_antes from acaimix.produtos where id = v_id and not arquivado for update;
    if not found then perform acaimix.erro('Produto não encontrado.', 404); end if;
    update acaimix.produtos set categoria_id = (p->>'categoria_id')::bigint, nome = p->>'nome', descricao = p->>'descricao',
      preco_centavos = v_preco, emoji = p->>'emoji', disponivel = v_disp,
      permite_adicionais = (p->>'permite_adicionais')::boolean, destaque = (p->>'destaque')::boolean
    where id = v_id;
    if v_antes.preco_centavos <> v_preco then v_mud := v_mud || format('preço %s → %s', acaimix.reais(v_antes.preco_centavos), acaimix.reais(v_preco)); end if;
    if v_antes.nome <> p->>'nome' then v_mud := v_mud || format('nome "%s" → "%s"', v_antes.nome, p->>'nome'); end if;
    if v_antes.disponivel <> v_disp then v_mud := v_mud || case when v_disp then 'voltou ao cardápio' else 'tirado do cardápio' end; end if;
    perform acaimix.registrar(p->>'usuario', 'editou produto',
      (p->>'nome') || case when cardinality(v_mud) > 0 then ': ' || array_to_string(v_mud, '; ') else '' end, p->>'ip');
  end if;
  return jsonb_build_object('id', v_id);
end $$;

