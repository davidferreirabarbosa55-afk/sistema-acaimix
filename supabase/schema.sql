-- ---------------------------------------------------------------- utilidades internas
create or replace function acaimix.iso(t timestamptz) returns text
language sql immutable set search_path = '' as
$$ select to_char(t at time zone 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"') $$;

create or replace function acaimix.reais(c int) returns text
language sql immutable set search_path = '' as
$$ select 'R$ ' || replace(to_char(c / 100.0, 'FM999999990.00'), '.', ',') $$;

create or replace function acaimix.erro(msg text, status int default 400) returns void
language plpgsql set search_path = '' as
$$ begin
  -- "PTxxx" faz a API do Supabase responder com o status HTTP xxx.
  raise exception using message = msg, errcode = 'PT' || status::text;
end $$;

create or replace function acaimix.registrar(p_usuario text, p_acao text, p_detalhe text, p_ip text) returns void
language sql set search_path = '' as
$$ insert into acaimix.auditoria (usuario, acao, detalhe, ip)
   values (coalesce(nullif(p_usuario, ''), '-'), p_acao, left(coalesce(p_detalhe, ''), 300), coalesce(p_ip, '')) $$;

create or replace function acaimix.cfg(p_chave text) returns text
language sql stable set search_path = '' as
$$ select valor from acaimix.configuracoes where chave = p_chave $$;

create or replace function acaimix.itens_json(p_pedido bigint) returns jsonb
language sql stable set search_path = '' as
$$ select coalesce(jsonb_agg(jsonb_build_object(
     'produto_id', produto_id, 'nome', nome, 'preco_centavos', preco_centavos,
     'quantidade', quantidade, 'observacao', observacao, 'adicionais', adicionais) order by id), '[]'::jsonb)
   from acaimix.itens_pedido where pedido_id = p_pedido $$;

