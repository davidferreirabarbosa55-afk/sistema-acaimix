language sql stable set search_path = '' as
$$ select jsonb_build_object(
     'codigo', p.codigo, 'status', p.status, 'cliente_nome', p.cliente_nome, 'tipo', p.tipo, 'mesa', p.mesa,
     'forma_pagamento', p.forma_pagamento, 'total_centavos', p.total_centavos, 'criado_em', acaimix.iso(p.criado_em),
     'itens', (select coalesce(jsonb_agg(jsonb_build_object('nome', nome, 'preco_centavos', preco_centavos,
                 'quantidade', quantidade, 'observacao', observacao, 'adicionais', adicionais) order by id), '[]'::jsonb)
               from acaimix.itens_pedido where pedido_id = p.id),
     'pagamento', (select jsonb_build_object('metodo', metodo, 'status', status, 'pix_copia_cola', pix_copia_cola,
                     'pix_qr_base64', pix_qr_base64, 'checkout_url', checkout_url)
                   from acaimix.pagamentos where pedido_id = p.id order by id desc limit 1)) $$;

