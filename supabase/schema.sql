create or replace function public.api_mudar_status(p jsonb) returns jsonb
language plpgsql set search_path = '' as $$
declare v acaimix.pedidos; v_novo text := p->>'status'; v_permitidos text[];
begin
  select * into v from acaimix.pedidos where id = (p->>'id')::bigint for update;
  if not found then perform acaimix.erro('Pedido não encontrado.', 404); end if;
  v_permitidos := case v.status
    when 'recebido'   then array['em_preparo','cancelado']
    when 'em_preparo' then array['pronto','recebido','cancelado']
    when 'pronto'     then array['entregue','em_preparo']
    when 'entregue'   then array['pronto']
    else array[]::text[] end;
  if not (v_novo = any(v_permitidos)) then perform acaimix.erro('Mudança de status não permitida.'); end if;
  if v_novo = 'cancelado' then
    perform acaimix.registrar(p->>'usuario', 'cancelou pedido',
      format('%s (%s, %s)', v.codigo, acaimix.reais(v.total_centavos),
             case v.forma_pagamento when 'pix' then 'Pix' when 'cartao' then 'cartão' else 'balcão' end)
      || case when v.forma_pagamento = 'balcao' then '' else ' — já estava pago: reembolsar no Mercado Pago' end, p->>'ip');
  end if;
  update acaimix.pedidos set status = v_novo, atualizado_em = now() where id = v.id returning * into v;
  return acaimix.pedido_json(v);
end $$;

