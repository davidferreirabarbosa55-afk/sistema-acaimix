language sql stable set search_path = '' as
$$ select jsonb_build_object(
     'id', p.id, 'codigo', p.codigo, 'status', p.status, 'cliente_nome', p.cliente_nome,
     'tipo', p.tipo, 'mesa', p.mesa, 'observacao', p.observacao, 'forma_pagamento', p.forma_pagamento,
     'total_centavos', p.total_centavos, 'criado_em', acaimix.iso(p.criado_em), 'atualizado_em', acaimix.iso(p.atualizado_em),
