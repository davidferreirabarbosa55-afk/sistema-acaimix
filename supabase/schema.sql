-- ---------------------------------------------------------------- limite de tentativas por IP
create or replace function public.api_limitar(p jsonb) returns jsonb
language plpgsql set search_path = '' as $$
declare v_n int;
begin
  insert into acaimix.limites as l (chave, inicio, n) values (p->>'chave', now(), 1)
  on conflict (chave) do update set
    n      = case when now() - l.inicio > make_interval(secs => (p->>'janela_seg')::int) then 1 else l.n + 1 end,
    inicio = case when now() - l.inicio > make_interval(secs => (p->>'janela_seg')::int) then now() else l.inicio end
  returning n into v_n;
  return to_jsonb(v_n <= (p->>'max')::int);
end $$;

